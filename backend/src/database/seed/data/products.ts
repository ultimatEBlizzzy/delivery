export type Shape =
  | 'bag'
  | 'box'
  | 'bucket'
  | 'pipe'
  | 'sheet'
  | 'brick'
  | 'tool'
  | 'bulb'
  | 'roll'
  | 'bolt'
  | 'tap'
  | 'generic';

export interface SeedProduct {
  sku: string;
  name: string;
  /** Sub-category (or top-level category when it has no children). */
  category: string;
  unit: string;
  packSize?: string;
  weightKg: number;
  /** Length × width × height of one unit in cm. */
  dims?: [number, number, number];
  /** Fictional brand. */
  brand: string;
  /** Typical Rand price – each store applies its own factor. */
  price: number;
  shape: Shape;
  /** Customers usually buy this in volume (bricks, blocks…): listings get a higher minimum order. */
  bulk?: number;
}

